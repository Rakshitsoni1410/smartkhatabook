import 'package:flutter/material.dart';
import 'package:intl/intl.dart';
import 'package:printing/printing.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../models/order.dart';
import '../services/api_client.dart';

class BillingScreen extends StatefulWidget {
  final String userId;
  final String userRole;

  const BillingScreen({
    super.key,
    required this.userId,
    required this.userRole,
  });

  @override
  State<BillingScreen> createState() => _BillingScreenState();
}

class _BillingScreenState extends State<BillingScreen> {
  bool _loading = true;
  String? _error;
  List<Order> _orders = [];

  bool get _isWholesaler {
    final role = widget.userRole.trim().toLowerCase();
    return role == 'wholesaler' || role == 'owner';
  }

  @override
  void initState() {
    super.initState();
    _loadBills();
  }

  Future<void> _loadBills() async {
    setState(() {
      _loading = true;
      _error = null;
    });
    try {
      final path = _isWholesaler
          ? '/orders/billing/wholesaler/${widget.userId}'
          : '/orders/billing/retailer/${widget.userId}';
      final response = await ApiClient.get(path);
      final raw =
          response['data'] ?? response['orders'] ?? response['bills'] ?? [];
      final list = raw is List ? raw : [];
      if (!mounted) return;
      setState(() {
        _orders = list
            .whereType<Map>()
            .map((item) => Order.fromJson(Map<String, dynamic>.from(item)))
            .toList();
        _loading = false;
      });
    } on ApiException catch (error) {
      if (!mounted) return;
      setState(() {
        _error = error.message;
        _loading = false;
      });
    }
  }

  Future<void> _sendBill(Order order) async {
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (context) => AlertDialog(
        title: const Text('Send this bill to retailer?'),
        content: Text(
          'Invoice: ${order.invoiceNumber ?? 'Generated by backend'}\n'
          'Product: ${order.productName}\n'
          'Amount: ${_money(order.totalAmount)}',
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context, false),
            child: const Text('Cancel'),
          ),
          FilledButton(
            onPressed: () => Navigator.pop(context, true),
            child: const Text('Confirm & Send'),
          ),
        ],
      ),
    );
    if (confirmed != true || order.id.isEmpty) return;

    try {
      await ApiClient.patch('/orders/${order.id}/send-bill');
      if (!mounted) return;
      ScaffoldMessenger.of(
        context,
      ).showSnackBar(const SnackBar(content: Text('Bill sent successfully')));
      await _loadBills();
    } on ApiException catch (error) {
      if (mounted)
        ScaffoldMessenger.of(
          context,
        ).showSnackBar(SnackBar(content: Text(error.message)));
    }
  }

  String _money(double value) => '₹${NumberFormat('#,##0.00').format(value)}';

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: const Text('Billing'),
        actions: [
          IconButton(onPressed: _loadBills, icon: const Icon(Icons.refresh)),
        ],
      ),
      body: _loading
          ? const Center(child: CircularProgressIndicator())
          : _error != null
          ? _ErrorState(message: _error!, onRetry: _loadBills)
          : _orders.isEmpty
          ? Center(
              child: Text(
                _isWholesaler
                    ? 'No billing records yet'
                    : 'No bills have been sent to you',
              ),
            )
          : RefreshIndicator(
              onRefresh: _loadBills,
              child: ListView.builder(
                padding: const EdgeInsets.all(16),
                itemCount: _orders.length,
                itemBuilder: (_, index) => _billCard(_orders[index]),
              ),
            ),
    );
  }

  Widget _billCard(Order order) {
    final delivered = [
      'delivered',
      'completed',
    ].contains(order.orderStatus.toLowerCase());
    final party = _isWholesaler
        ? _partyName(order.retailerId, order, 'Retailer', 'retailerName')
        : _partyName(order.wholesalerId, order, 'Wholesaler', 'wholesalerName');
    return Card(
      margin: const EdgeInsets.only(bottom: 12),
      child: Padding(
        padding: const EdgeInsets.all(16),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              children: [
                const Icon(
                  Icons.receipt_long_outlined,
                  color: Color(0xff2563EB),
                ),
                const SizedBox(width: 10),
                Expanded(
                  child: Text(
                    order.invoiceNumber ??
                        (delivered
                            ? 'Invoice pending'
                            : 'Available after delivery'),
                    style: const TextStyle(fontWeight: FontWeight.bold),
                  ),
                ),
                _statusChip(order.orderStatus),
              ],
            ),
            const SizedBox(height: 10),
            Text(party, style: const TextStyle(fontWeight: FontWeight.w600)),
            const SizedBox(height: 4),
            Text(
              '${order.productName}  •  ${_quantity(order.quantity)} ${order.unit}',
            ),
            Text(
              '${_money(order.pricePerUnit)} per unit  •  ${_money(order.totalAmount)}',
            ),
            if (order.createdAt != null)
              Text(DateFormat('dd MMM yyyy').format(order.createdAt!)),
            const SizedBox(height: 12),
            Row(
              children: [
                OutlinedButton.icon(
                  onPressed: delivered
                      ? () => Navigator.push(
                          context,
                          MaterialPageRoute(
                            builder: (_) => InvoiceScreen(
                              order: order,
                              partyName: party,
                              isWholesaler: _isWholesaler,
                            ),
                          ),
                        )
                      : null,
                  icon: const Icon(Icons.visibility_outlined),
                  label: const Text('View invoice'),
                ),
                if (_isWholesaler &&
                    delivered &&
                    !order.billSentToRetailer) ...[
                  const SizedBox(width: 8),
                  Expanded(
                    child: FilledButton.icon(
                      onPressed: () => _sendBill(order),
                      icon: const Icon(Icons.send_outlined),
                      label: const Text('Send bill'),
                    ),
                  ),
                ] else if (_isWholesaler && order.billSentToRetailer) ...[
                  const SizedBox(width: 8),
                  const Chip(
                    avatar: Icon(Icons.check, size: 16, color: Colors.green),
                    label: Text('Sent'),
                  ),
                ],
              ],
            ),
          ],
        ),
      ),
    );
  }

  String _quantity(double value) => value == value.roundToDouble()
      ? value.toStringAsFixed(0)
      : value.toStringAsFixed(2);

  String _name(dynamic value, String fallback) {
    if (value is Map)
      return value['shopName']?.toString().isNotEmpty == true
          ? value['shopName'].toString()
          : value['name']?.toString() ?? fallback;
    return fallback;
  }

  String _partyName(
    dynamic value,
    Order order,
    String fallback,
    String nameField,
  ) {
    final populatedName = _name(value, '');
    if (populatedName.isNotEmpty) return populatedName;
    final explicitName = nameField == 'retailerName'
        ? order.retailerName
        : order.wholesalerName;
    return explicitName?.isNotEmpty == true ? explicitName! : fallback;
  }

  Widget _statusChip(String status) =>
      Chip(label: Text(status.isEmpty ? 'pending' : status));
}

class _ErrorState extends StatelessWidget {
  final String message;
  final VoidCallback onRetry;

  const _ErrorState({required this.message, required this.onRetry});

  @override
  Widget build(BuildContext context) => Center(
    child: Column(
      mainAxisSize: MainAxisSize.min,
      children: [
        Text(message, textAlign: TextAlign.center),
        const SizedBox(height: 12),
        FilledButton(onPressed: onRetry, child: const Text('Retry')),
      ],
    ),
  );
}

class InvoiceScreen extends StatelessWidget {
  final Order order;
  final String partyName;
  final bool isWholesaler;

  const InvoiceScreen({
    super.key,
    required this.order,
    required this.partyName,
    required this.isWholesaler,
  });

  String _money(double value) => '₹${NumberFormat('#,##0.00').format(value)}';

  Future<void> _print() async {
    final document = pw.Document();
    document.addPage(
      pw.Page(
        pageFormat: PdfPageFormat.a4,
        build: (_) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text(
              'SMART KHATA BOOK',
              style: pw.TextStyle(fontSize: 22, fontWeight: pw.FontWeight.bold),
            ),
            pw.SizedBox(height: 18),
            pw.Text('Invoice Number: ${order.invoiceNumber ?? 'Pending'}'),
            pw.Text(
              'Invoice Date: ${order.createdAt == null ? '-' : DateFormat('dd MMM yyyy').format(order.createdAt!)}',
            ),
            pw.SizedBox(height: 18),
            pw.Text(
              '${isWholesaler ? 'Retailer / Buyer' : 'Wholesaler / Seller'}: $partyName',
            ),
            pw.SizedBox(height: 18),
            pw.Table.fromTextArray(
              headers: ['Product', 'Quantity', 'Unit', 'Price', 'Total'],
              data: [
                [
                  order.productName,
                  '${order.quantity}',
                  order.unit,
                  _money(order.pricePerUnit),
                  _money(order.totalAmount),
                ],
              ],
            ),
            pw.SizedBox(height: 18),
            pw.Text(
              'Advance Paid: ${_money(order.advancePaid ? order.advanceAmount : 0)}',
            ),
            pw.Text('Remaining Amount: ${_money(order.remainingAmount)}'),
            pw.Text('Payment Status: ${order.paymentStatus}'),
            pw.Text('Order Status: ${order.orderStatus}'),
          ],
        ),
      ),
    );
    await Printing.layoutPdf(onLayout: (_) async => document.save());
  }

  @override
  Widget build(BuildContext context) => Scaffold(
    appBar: AppBar(
      title: const Text('Invoice'),
      actions: [
        IconButton(
          onPressed: _print,
          tooltip: 'Print or save PDF',
          icon: const Icon(Icons.print_outlined),
        ),
      ],
    ),
    body: ListView(
      padding: const EdgeInsets.all(20),
      children: [
        const Text(
          'SMART KHATA BOOK',
          style: TextStyle(fontSize: 24, fontWeight: FontWeight.bold),
        ),
        const SizedBox(height: 18),
        _row('Invoice Number', order.invoiceNumber ?? 'Pending'),
        _row(
          'Invoice Date',
          order.createdAt == null
              ? '-'
              : DateFormat('dd MMM yyyy').format(order.createdAt!),
        ),
        _row(
          isWholesaler ? 'Retailer / Buyer' : 'Wholesaler / Seller',
          partyName,
        ),
        const Divider(height: 28),
        _row('Product', order.productName),
        _row('Quantity', '${order.quantity} ${order.unit}'),
        _row('Price Per Unit', _money(order.pricePerUnit)),
        _row('Total Amount', _money(order.totalAmount)),
        _row(
          'Advance Paid',
          _money(order.advancePaid ? order.advanceAmount : 0),
        ),
        _row('Remaining Amount', _money(order.remainingAmount)),
        _row('Payment Status', order.paymentStatus),
        _row('Order Status', order.orderStatus),
      ],
    ),
  );

  Widget _row(String label, String value) => Padding(
    padding: const EdgeInsets.only(bottom: 12),
    child: Row(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        SizedBox(
          width: 145,
          child: Text(
            label,
            style: const TextStyle(fontWeight: FontWeight.w600),
          ),
        ),
        Expanded(child: Text(value)),
      ],
    ),
  );
}
